# ------------------ IMAGE UPLOAD ------------------
st.markdown("<h3>📤 Upload Retinal Image</h3>", unsafe_allow_html=True)

uploaded_file = st.file_uploader(
    "Upload a retinal image (JPG, JPEG, PNG)",
    type=["jpg", "jpeg", "png"]
)

# ------------------ PREDICTION ------------------
if uploaded_file is not None:
    image = Image.open(uploaded_file).convert("RGB")

    st.markdown("<div class='card'>", unsafe_allow_html=True)
    st.image(image, caption="Uploaded Retinal Image", use_container_width=True)
    st.markdown("</div>", unsafe_allow_html=True)

    with st.spinner("🔍 Analyzing image, please wait..."):
        img_input = preprocess_image(image)
        prediction = model.predict(img_input)
        predicted_class = np.argmax(prediction)
        confidence = np.max(prediction) * 100

        label, simple_msg = class_labels[predicted_class]

    # ------------------ RESULT ------------------
    st.markdown("""
    <div class="card">
    <h3>📊 Diagnosis Result</h3>
    </div>
    """, unsafe_allow_html=True)

    st.success(f"**Detected Condition:** {label}")
    st.info(f"**Patient Message:** {simple_msg}")
    st.warning(f"**Prediction Confidence:** {confidence:.2f}%")

    st.markdown("""
    <p style="color:#dddddd;">
    ⚠ This result is generated by an AI system and is not a final medical diagnosis.
    Please consult a certified eye specialist for confirmation.
    </p>
    """, unsafe_allow_html=True)


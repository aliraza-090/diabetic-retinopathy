# ------------------ LOAD MODEL ------------------
@st.cache_resource
def load_model():
    return tf.keras.models.load_model("saved_models/model_trained.h5")

model = load_model()

# ------------------ CLASS LABELS ------------------
class_labels = {
    0: ("No DR", "Your retinal image appears healthy. No signs of diabetic retinopathy detected."),
    1: ("Mild DR", "Early signs detected. It is recommended to consult an eye specialist."),
    2: ("Moderate DR", "Noticeable retinal damage detected. Medical consultation is strongly advised."),
    3: ("Severe DR", "Severe retinal damage detected. Immediate medical attention is required.")
}

# ------------------ IMAGE PREPROCESS ------------------
def preprocess_image(image):
    image = image.resize((224, 224))
    img_array = np.array(image) / 255.0
    img_array = np.expand_dims(img_array, axis=0)
    return img_array

